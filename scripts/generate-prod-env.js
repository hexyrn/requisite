#!/usr/bin/env node
/**
 * Creates the production `.env` for docker-compose.prod.yml with fresh random
 * secrets, so nobody has to hand-craft (or reuse) seven of them.
 *
 *   node scripts/generate-prod-env.js --host hexyrn.example.com --generate-licence-keys ./licence-keys
 *   node scripts/generate-prod-env.js --host localhost --licence-public-key <base64-from-licence-tool>
 *
 * --host                    DNS name users will type (Caddy gets a Let's Encrypt cert for a
 *                           real name; "localhost" gets a self-signed one). Default: localhost
 * --licence-public-key      HEXYRN_LICENSE_PUBLIC_KEY from an existing `licence-tool keygen`
 * --generate-licence-keys D create the licence signing keypair in directory D and use its public
 *                           key (you are the vendor AND the operator). Keep D's private key OFFLINE.
 * --out FILE                default: .env  (never overwritten; move the old one first)
 *
 * Zero dependencies on purpose (plain Node) so it runs before `npm install`.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

function parse(argv) {
  const f = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--'))
      f[argv[i].slice(2)] = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : 'true';
  }
  return f;
}
const b64 = (n) => crypto.randomBytes(n).toString('base64');
// URL-safe: these end up inside postgres:// connection URIs.
const pw = () => crypto.randomBytes(32).toString('base64url');

function main() {
  const f = parse(process.argv.slice(2));
  const out = path.resolve(f.out && f.out !== 'true' ? f.out : '.env');
  if (fs.existsSync(out)) {
    throw new Error(
      `${out} already exists - refusing to overwrite secrets. Move or delete it first.`,
    );
  }
  if (f['licence-public-key'] && f['generate-licence-keys']) {
    throw new Error('use either --licence-public-key or --generate-licence-keys, not both.');
  }
  const host = f.host && f.host !== 'true' ? f.host : 'localhost';
  if (!/^[a-z0-9.-]+$/i.test(host))
    throw new Error(`--host "${host}" is not a plain host name (no scheme, port or path).`);

  let licenceKey = f['licence-public-key'];
  let generatedDir = null;
  if (f['generate-licence-keys']) {
    generatedDir = path.resolve(f['generate-licence-keys']);
    const privPath = path.join(generatedDir, 'licence-private.pem');
    if (fs.existsSync(privPath))
      throw new Error(`${privPath} already exists - refusing to overwrite a signing key.`);
    fs.mkdirSync(generatedDir, { recursive: true });
    const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');
    fs.writeFileSync(privPath, privateKey.export({ type: 'pkcs8', format: 'pem' }), {
      mode: 0o600,
    });
    const pubPem = publicKey.export({ type: 'spki', format: 'pem' }).toString();
    fs.writeFileSync(path.join(generatedDir, 'licence-public.pem'), pubPem);
    licenceKey = pubPem.replace(/-----(BEGIN|END) PUBLIC KEY-----/g, '').replace(/\s+/g, '');
  }
  if (!licenceKey || licenceKey === 'true') {
    throw new Error(
      'a licence public key is required: pass --licence-public-key <value> or --generate-licence-keys <dir>.',
    );
  }

  const lines = [
    '# Generated by scripts/generate-prod-env.js - contains SECRETS. Back it up somewhere safe;',
    '# losing TOTP_MASTER_KEY_CURRENT / SECRET_ENCRYPTION_MASTER_KEY makes stored MFA and SMTP secrets unrecoverable.',
    `HEXYRN_PUBLIC_HOSTNAME=${host}`,
    `POSTGRES_PASSWORD=${pw()}`,
    `HEXYRN_APP_DB_PASSWORD=${pw()}`,
    `HEXYRN_BACKUP_DB_PASSWORD=${pw()}`,
    `HEXYRN_SESSION_SECRET=${b64(48)}`,
    `TOTP_MASTER_KEY_CURRENT=${b64(32)}`,
    `SECRET_ENCRYPTION_MASTER_KEY=${b64(32)}`,
    `HEXYRN_LICENSE_PUBLIC_KEY=${licenceKey}`,
    '',
  ];
  fs.writeFileSync(out, lines.join('\n'), { mode: 0o600 });
  console.log(`Wrote ${out}`);
  if (generatedDir) {
    console.log(
      `Licence signing keys in ${generatedDir}  (licence-private.pem is your vendor key: keep it OFFLINE, never deploy or commit it)`,
    );
  }
  console.log('\nNext:\n  docker compose -f docker-compose.prod.yml up -d --build');
}

try {
  main();
} catch (e) {
  console.error(`Error: ${e.message}`);
  process.exit(1);
}
